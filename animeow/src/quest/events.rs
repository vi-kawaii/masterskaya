use bevy::prelude::*;

/// События мира, на которые реагируют квесты.
///
/// Кто угодно в игре пишет сюда: диалоги — `TalkedTo`,
/// триггеры в мире — `ReachedLocation`, будущие боты — `Killed`,
/// инвентарь — `Collected`.
///
/// Квест-трекер читает эти события и двигает шаги.
/// Развязка: квесты не знают про диалоги, диалоги не знают про квесты.
#[derive(Message, Debug, Clone)]
pub enum QuestEvent {
    /// Игрок дослушал/выбрал реплику с данным id (id узла диалога или NPC).
    TalkedTo(String),
    /// Игрок вошёл в зону с данным id.
    ReachedLocation(String),
    /// Игрок убил существо типа `kind`. Счётчик инкрементируется.
    Killed(String),
    /// Игрок подобрал предмет `item_id`. Счётчик инкрементируется.
    Collected(String),
}